"""Write mesa/darwin/sweetgl/sweetca_slots.inc: names of the 1036 GLI dispatch slots (libsweetca's
trap functions log them). Names come from OpenGLES's exported gl* thunks (glimap.py) and from
GLEngine's gliInitDispatchTable (glislots.py output in ~/ios-work/gl/out2/glislots.txt); slots
neither knows stay unnamed. Run in WSL from tools/g2/dsc:
  python3 glislots.py > ~/ios-work/gl/out2/glislots.txt
  python3 genslots.py ../../../mesa/darwin/sweetgl/sweetca_slots.inc
"""
import os
import sys

import glimap

N = 1036
BS = chr(92)
names = {}
for line in open(os.path.expanduser('~/ios-work/gl/out2/glislots.txt')):
    i, _, n = line.split()
    if n.startswith('_gl'):
        names[int(i)] = n[1:].removesuffix('_Exec')
for off, ns in glimap.off2name.items():
    # glimap offsets are offsets in {rctx; disp[]}: slot = (off - 8) / 8
    names[(off - 8) // 8] = '/'.join(ns)
out = ['/* generated by tools/g2/dsc/genslots.py from GLEngine and OpenGLES (iOS 16.7.16): slot -> GL name */',
       '#define SCA_SLOTS %d' % N, '', 'static const char *const sca_slot_names[SCA_SLOTS] = {']
for i in range(N):
    if names.get(i):
        out.append('\t[%d] = "%s",' % (i, names[i]))
out.append('};')
out.append('')
out.append('#define SCA_FOR_EACH_SLOT(T) ' + BS)
for i in range(N):
    out.append('\tT(%d)%s' % (i, (' ' + BS) if i < N - 1 else ''))
open(sys.argv[1], 'w', newline='\n').write('\n'.join(out) + '\n')
print(len(names), 'named slots')
